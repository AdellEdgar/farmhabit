/** Una frase de la especie para ese momento: la misma semilla da siempre la misma. */
export function pickPhrase(species: SpeciesId, moment: PhraseMoment, seed: string): string {
  const list = PHRASES[species][moment];
  return list[Math.floor(stableRandom(seed) * list.length)]!;
}
